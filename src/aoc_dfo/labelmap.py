"""CCO label shorthand ↔ CCO 2.x IRIs (MR-9).

Spec text writes ``cco:InformationContentEntity``; CCO 2.x mints opaque IRIs such as
``…/ont00000958``. This module resolves every ``cco:`` token in the spec against the pinned CCO
file by label, so a name that does not exist in CCO 2.2 (for example ``cco:MilitaryOrganization``)
fails CI instead of surviving as a plausible-looking typo.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from rdflib import OWL, RDF, RDFS, Graph, URIRef

from . import SPEC_DIR
from .pins import load_pins

TOKEN = re.compile(r"\bcco:([A-Za-z][A-Za-z_]*)")


def _norm(s: str) -> str:
    return re.sub(r"[\s_\-]", "", s).lower()


@dataclass(frozen=True)
class Term:
    shorthand: str
    label: str
    iri: str
    kind: str


def load_cco() -> Graph:
    pin = next(p for p in load_pins() if p.name == "CCO")
    return Graph().parse(pin.path, format="turtle")


def label_index(g: Graph) -> dict[str, list[tuple[URIRef, str, str]]]:
    idx: dict[str, list[tuple[URIRef, str, str]]] = {}
    for s, label in g.subject_objects(RDFS.label):
        if not isinstance(s, URIRef):
            continue
        if (s, RDF.type, OWL.Class) in g:
            kind = "class"
        elif (s, RDF.type, OWL.ObjectProperty) in g:
            kind = "object property"
        elif (s, RDF.type, OWL.DatatypeProperty) in g:
            kind = "datatype property"
        elif (s, RDF.type, OWL.AnnotationProperty) in g:
            kind = "annotation property"
        else:
            continue
        idx.setdefault(_norm(str(label)), []).append((s, str(label), kind))
    return idx


def spec_tokens(spec_dir: Path = SPEC_DIR) -> set[str]:
    tokens: set[str] = set()
    for md in sorted(spec_dir.rglob("*.md")):
        tokens.update(TOKEN.findall(md.read_text(encoding="utf-8")))
    return tokens


def resolve_tokens(tokens: set[str], g: Graph | None = None) -> tuple[list[Term], list[str]]:
    idx = label_index(g if g is not None else load_cco())
    found, missing = [], []
    for tok in sorted(tokens):
        hits = idx.get(_norm(tok), [])
        if len(hits) == 1:
            iri, label, kind = hits[0]
            found.append(Term(f"cco:{tok}", label, str(iri), kind))
        elif not hits:
            missing.append(f"cco:{tok}")
        else:
            missing.append(f"cco:{tok} (ambiguous: {[str(h[0]) for h in hits]})")
    return found, missing


def render_markdown(terms: list[Term]) -> str:
    lines = [
        "# CCO label map",
        "",
        "Generated by `uv run aoc-dfo labelmap` from the pinned CCO v2.2 file. Do not edit by hand.",
        "Every `cco:` shorthand used in the spec resolves here to exactly one CCO 2.2 term (MR-9).",
        "",
        "| Spec shorthand | CCO 2.2 label | IRI | Kind |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| `{t.shorthand}` | {t.label} | `{t.iri}` | {t.kind} |" for t in terms]
    return "\n".join(lines) + "\n"
